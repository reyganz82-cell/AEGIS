// ------------------------------------------------------------------ state
function detect() {
  if (typeof window === "undefined") return "id"; // Node/test: deterministik
  try { const s = localStorage.getItem("aegis.lang"); if (D[s]) return s; } catch { /* storage tidak tersedia */ }
  return /^en/i.test(navigator.language || "") ? "en" : "id";
}

let lang = detect();
const listeners = new Set();

export const getLang = () => lang;
export const meta = () => LANGS[lang];

export function setLang(next) {
  if (!D[next] || next === lang) return false;
  lang = next;
  try { localStorage.setItem("aegis.lang", next); } catch { /* abaikan */ }
  listeners.forEach((fn) => { try { fn(next); } catch (e) { console.error("[i18n]", e); } });
  return true;
}

export function onLangChange(fn) { listeners.add(fn); return () => listeners.delete(fn); }

/** "3 orang" / "1 person" / "2 people" */
export const peopleText = (n) => (lang === "en" ? (n === 1 ? "1 person" : `${n} people`) : `${n} orang`);

/** Terjemahkan kunci; {param} diganti dari vars. Kunci tak dikenal dikembalikan apa adanya. */
export function t(key, vars) {
  let s = D[lang][key] ?? D.id[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
  return s;
}
